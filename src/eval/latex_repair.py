"""
LaTeX Syntax Auto-Repair & Stack-Based AST Validator for HMER.

Defensively repairs malformed or incomplete LaTeX math output generated by deep learning decoders
before rendering or SymPy compilation:
1. Balances unclosed curly braces '{' and '}'.
2. Balances unclosed parentheses '(' and ')' or brackets '[' and ']'.
3. Matches orphan '\\left' with corresponding '\\right' delimiters.
4. Cleans dangling script markers ('^', '_') at the end of token sequences.
"""

import re
from typing import List, Tuple


def balance_brackets(latex_str: str) -> str:
    """
    Balances unclosed curly braces '{}', round brackets '()', and square brackets '[]'.
    """
    repaired = latex_str
    
    # 1. Curly Braces {}
    open_curly = repaired.count("{") - repaired.count(r"\{")
    close_curly = repaired.count("}") - repaired.count(r"\}")
    if open_curly > close_curly:
        repaired += "}" * (open_curly - close_curly)

    # 2. Parentheses ()
    open_paren = repaired.count("(") - repaired.count(r"\(")
    close_paren = repaired.count(")") - repaired.count(r"\)")
    if open_paren > close_paren:
        repaired += ")" * (open_paren - close_paren)

    # 3. Square Brackets []
    open_bracket = repaired.count("[") - repaired.count(r"\[")
    close_bracket = repaired.count("]") - repaired.count(r"\]")
    if open_bracket > close_bracket:
        repaired += "]" * (open_bracket - close_bracket)

    return repaired


def match_left_right_delimiters(latex_str: str) -> str:
    """
    Matches orphan '\\left' commands with corresponding '\\right.' fallbacks.
    """
    num_left = len(re.findall(r"\\left\b", latex_str))
    num_right = len(re.findall(r"\\right\b", latex_str))
    
    if num_left > num_right:
        latex_str += r" \right." * (num_left - num_right)
        
    return latex_str


def clean_dangling_operators(latex_str: str) -> str:
    """
    Removes trailing dangling operators or sub/superscript markers.
    """
    # Remove trailing ^ or _ without arguments
    latex_str = re.sub(r"[\^\_]\s*$", "", latex_str)
    # Remove trailing \frac or \sqrt without braces
    latex_str = re.sub(r"\\(?:frac|sqrt)\s*$", "", latex_str)
    return latex_str


def repair_latex_syntax(latex_str: str) -> str:
    """
    Master pipeline for auto-repairing LaTeX string syntax.
    """
    repaired = latex_str.strip()
    repaired = clean_dangling_operators(repaired)
    repaired = match_left_right_delimiters(repaired)
    repaired = balance_brackets(repaired)
    return repaired


